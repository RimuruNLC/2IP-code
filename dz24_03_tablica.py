import pandas as pd
tablica =  pd.read_excel("1s.xlsx")
print(tablica)
mean1 = tablica[["Предмет1","Предмет2","Предмет3","Предмет4","Предмет5"]].mean()
print("Средний балл всей группы:", mean1.mean())
print("Ученики не имеющие троек:")
print(tablica[tablica[["Предмет1","Предмет2","Предмет3","Предмет4","Предмет5"]].min(axis=1)>3])
print("Вывод всех учеников без стипендии")
print(tablica[tablica["stepen"]==0])
print("Ученики проживающие в Шумерле и имеющие средний балл 4.5 или выше")
print(tablica[(tablica["Город проживания"]=="Шумерля") & (tablica[["Предмет1","Предмет2","Предмет3","Предмет4","Предмет5"]].mean(axis=1)>4.5)])
print("Средний балл всех предметов\n",tablica[["Предмет1","Предмет2","Предмет3","Предмет4","Предмет5"]].mean())
print(tablica[(tablica["Город проживания"]!="Шумерля") & (tablica[["Предмет1","Предмет2","Предмет3","Предмет4","Предмет5"]].max(axis=1)==5)])
print("Общее количество троек учеников без стипендии")
a = tablica[tablica["stepen"]==0]
print(a["Предмет1"].value_counts()[3]+a["Предмет2"].value_counts()[3]+a["Предмет3"].value_counts()[3]+a["Предмет4"].value_counts()[3]+a["Предмет5"].value_counts()[3])
print("Выводит совершеннолетних учеников с средним балом 4.5 или выше")
print(tablica[(tablica["aga"]==18) & (tablica[["Предмет1","Предмет2","Предмет3","Предмет4","Предмет5"]].mean(axis=1)>=4)])
print("Выводит иногордних с повышенной стипендией")
print(tablica[(tablica["stepen"]>700) & (tablica["Город проживания"]!="Шумерля")])
